// Firebase is optional: the Google Services + Crashlytics plugins are applied only when a real
// configuration file is present. This keeps `./gradlew assembleRelease` working for contributors
// and CI forks that have no Firebase project, while a release build with google-services.json gets
// the full Crashlytics symbol upload.
val hasFirebaseConfig = file("google-services.json").exists()
if (hasFirebaseConfig) {
    apply(plugin = "com.google.gms.google-services")
    apply(plugin = "com.google.firebase.crashlytics")
}

android {
    namespace = "com.sportage.obd"
    compileSdk = 35

    // Release signing credentials are read from the environment first (CI) and then from
    // android/keystore.properties (local machines). Neither is ever committed.
    // With no credentials at all the release build stays unsigned instead of failing, so
    // ordinary local builds keep working without a keystore.
    val keystoreProps = Properties()
    val keystorePropsFile = rootProject.file("keystore.properties")
    if (keystorePropsFile.exists()) {
        keystorePropsFile.inputStream().use { keystoreProps.load(it) }
    }

    val envKeystorePath = System.getenv("SPORTAGE_KEYSTORE_FILE")
    val releaseStoreFile = when {
        !envKeystorePath.isNullOrBlank() -> rootProject.file(envKeystorePath)
        !keystoreProps.getProperty("storeFile").isNullOrBlank() ->
            rootProject.file(keystoreProps.getProperty("storeFile")!!)
        else -> null
    }
    val releaseStorePassword =
        System.getenv("SPORTAGE_KEYSTORE_PASSWORD") ?: keystoreProps.getProperty("storePassword")
    val releaseKeyAlias =
        System.getenv("SPORTAGE_KEY_ALIAS") ?: keystoreProps.getProperty("keyAlias")
    val releaseKeyPassword =
        System.getenv("SPORTAGE_KEY_PASSWORD") ?: keystoreProps.getProperty("keyPassword")

    val hasReleaseKeystore = releaseStoreFile?.exists() == true &&
        !releaseStorePassword.isNullOrBlank() &&
        !releaseKeyAlias.isNullOrBlank() &&
        !releaseKeyPassword.isNullOrBlank()

    // Every Play upload needs a monotonically increasing versionCode. CI passes the run number;
    // local builds fall back to the value in the version catalog.
    val buildVersionCode = System.getenv("SPORTAGE_VERSION_CODE")?.toIntOrNull() ?: 1
    val buildVersionName = System.getenv("SPORTAGE_VERSION_NAME") ?: "1.0.0"

    logger.lifecycle(
        if (hasReleaseKeystore) {
            "Release signing: ENABLED (${releaseStoreFile!!.name})"
        } else {
            "Release signing: no credentials - assembleRelease produces an UNSIGNED apk/AAB"
        }
    )
    logger.lifecycle(
        if (hasFirebaseConfig) {
            "Firebase: google-services.json found - Crashlytics/Analytics enabled"
        } else {
            "Firebase: no google-services.json - diagnostics compile but stay disabled"
        }
    )

    defaultConfig {
        applicationId = "com.sportage.obd"
        minSdk = 28 // Android 9+ as specified in PRD Section 1.1
        targetSdk = 35
        versionCode = buildVersionCode
        versionName = buildVersionName

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables {
            useSupportLibrary = true
        }
        // Keeps the AAB honest about which dependency versions shipped.
        dependenciesInfo {
            includeInApk = false
            includeInBundle = true
        }
    }

    signingConfigs {
        // The debug keystore is generated by AGP on demand; naming it explicitly means
        // `signingReport` and CI both show one predictable identity for debug artifacts.
        getByName("debug") {
            storeFile = file("${System.getProperty("user.home")}/.android/debug.keystore")
        }
        if (hasReleaseKeystore) {
            create("release") {
                storeFile = releaseStoreFile
                storePassword = releaseStorePassword
                keyAlias = releaseKeyAlias
                keyPassword = releaseKeyPassword
                // minSdk is 28, so APK Signature Scheme v2 alone is enough; JAR (v1) signing
                // only matters below Android 7.0 and AGP does not emit it above minSdk 24.
                enableV1Signing = false
                enableV2Signing = true
            }
        }
    }

    buildTypes {
        release {
            // Play Store releases must be shrunk: R8 removes unused Compose/Firebase code and
            // resource shrinking drops unused drawables and strings. proguard-rules.pro carries
            // the keep rules for the reflective Bluetooth fallback and the OBD model classes.
            isMinifyEnabled = true
            isShrinkResources = true
            isDebuggable = false
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            if (hasReleaseKeystore) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
        debug {
            applicationIdSuffix = ".debug"
            isDebuggable = true
        }
    }

    bundle {
        // Play generates one APK per ABI/locale from the AAB.
        language {
            enableSplit = true
        }
        density {
            enableSplit = true
        }
        abi {
            enableSplit = true
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlinOptions {
        jvmTarget = "17"
    }
    buildFeatures {
        compose = true
    }
    lint {
        // Lint failures block CI; the report is uploaded as an artifact for triage.
        abortOnError = true
        checkReleaseBuilds = true
        warningsAsErrors = false
    }
    testOptions {
        unitTests.isReturnDefaultValues = true
    }
    packaging {
        resources {
            excludes += setOf(
                "/META-INF/{AL2.0,LGPL2.1}",
                "/META-INF/DEPENDENCIES",
                "/META-INF/LICENSE*",
                "META-INF/versions/9/previous-compilation-data.bin"
            )
        }
    }
}

// ---------------------------------------------------------------------------------------------
// Bundled privacy policy: PRIVACY.md at the repository root is the single source of truth and is
// copied into assets at build time, so the in-app policy can never drift from the published one.
// ---------------------------------------------------------------------------------------------
val privacyAssetsDir = layout.buildDirectory.dir("generated/privacyAssets")
val copyPrivacyPolicy by tasks.registering(Copy::class) {
    from(rootProject.file("../PRIVACY.md"))
    into(privacyAssetsDir)
    rename { "privacy_policy.md" }
}
android.sourceSets.getByName("main").assets.srcDir(privacyAssetsDir)
tasks.named("preBuild") { dependsOn(copyPrivacyPolicy) }

